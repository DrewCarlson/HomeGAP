/**
 * Embeds the production dashboard bundle into the binary as generated Kotlin source so the
 * orchestrator ships as a single executable with no external asset directory.
 */
val generateWebAssets by tasks.registering {
    description = "Writes the dashboard bundle to a Kotlin source file."
    val outDir = generatedAssetsDir
    val distDir = project(":web").layout.buildDirectory.dir("vite/js/productionExecutable")
    outputs.dir(outDir)
    inputs.property("skipWeb", skipWeb)
    if (!skipWeb) {
        dependsOn(":web:jsBrowserProductionDist")
        inputs.dir(distDir)
    }
    doLast {
        val target = outDir.get().asFile.resolve("homegap/dashboard/WebAssets.kt")
        target.parentFile.mkdirs()
        val root = distDir.get().asFile
        // `.br` files are the brotli copies that vite.config.js writes. Each one goes with its file.
        val files = if (skipWeb) emptyList() else root.walkTopDown()
            .filter { it.isFile && it.extension != "br" }
            .sortedBy { it.path }
            .toList()
        val source = StringBuilder()
        source.appendLine("// GENERATED by :generateWebAssets. Do not edit.")
        source.appendLine("package homegap.dashboard")
        source.appendLine()
        source.appendLine("internal object WebAssets {")
        source.appendLine("    val files: Map<String, WebAsset> by lazy {")
        source.appendLine("        mapOf(")
        files.forEachIndexed { index, file ->
            val path = "/" + file.relativeTo(root).invariantSeparatorsPath
            val gzip = if (file.extension in gzipExtensions) "gz$index()" else "null"
            val brotli = if (File("${file.path}.br").isFile) "br$index()" else "null"
            source.appendLine("            \"$path\" to WebAsset(\"$path\", asset$index(), $gzip, $brotli),")
        }
        source.appendLine("        )")
        source.appendLine("    }")
        files.forEachIndexed { index, file ->
            source.appendBase64Function("asset$index", file.readBytes())
            if (file.extension in gzipExtensions) {
                val compressed = ByteArrayOutputStream()
                GZIPOutputStream(compressed).use { it.write(file.readBytes()) }
                source.appendBase64Function("gz$index", compressed.toByteArray())
            }
            val brotliFile = File("${file.path}.br")
            if (brotliFile.isFile) {
                source.appendBase64Function("br$index", brotliFile.readBytes())
            }
        }
        source.appendLine("}")
        target.writeText(source.toString())
    }
}

/** Text assets also ship with a gzip copy, for clients that accept gzip. */
val gzipExtensions = setOf("js", "mjs", "css", "html", "svg", "json", "map", "wasm")

/** The longest string literal in a generated source file. */
val literalChunkSize = 30_000

/** Appends a private function [name] that returns [bytes] as Base64 text. */
fun StringBuilder.appendBase64Function(name: String, bytes: ByteArray) {
    appendLine("    private fun $name(): String = buildString {")
    Base64.getEncoder().encodeToString(bytes).chunked(literalChunkSize).forEach { chunk ->
        appendLine("        append(\"$chunk\")")
    }
    appendLine("    }")
}

/** Embeds the shipped data-center catalog (`locations/datacenters.yml`) in the binary. */
val generateLocations by tasks.registering {
    description = "Writes the data-center catalog to a Kotlin source file."
    val outDir = generatedLocationsDir
    val source = layout.projectDirectory.file("locations/datacenters.yml")
    inputs.file(source)
    outputs.dir(outDir)
    doLast {
        val target = outDir.get().asFile.resolve("homegap/locations/BuiltInLocations.kt")
        target.parentFile.mkdirs()
        val b64 = Base64.getEncoder().encodeToString(source.asFile.readBytes())
        target.writeText(buildString {
            appendLine("// GENERATED by :generateLocations from locations/datacenters.yml. Do not edit.")
            appendLine("package homegap.locations")
            appendLine()
            appendLine("internal object BuiltInLocations {")
            appendLine("    val yaml: String by lazy { kotlin.io.encoding.Base64.decode(BASE64).decodeToString() }")
            appendLine("    private const val BASE64 = \"$b64\"")
            appendLine("}")
        })
    }
}

tasks.matching { it.name.startsWith("compileKotlin") || it.name.endsWith("SourcesJar") }.configureEach {
    dependsOn(generateWebAssets, generateLocations)
}
