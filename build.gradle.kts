/**
 * Embeds the production dashboard bundle into the binary as generated Kotlin source so the
 * orchestrator ships as a single executable with no external asset directory.
 */
val generateWebAssets by tasks.registering {
    val outDir = generatedAssetsDir
    val distDir = project(":web").layout.buildDirectory.dir("vite/js/productionExecutable")
    outputs.dir(outDir)
    inputs.property("skipWeb", skipWeb)
    if (!skipWeb) {
        dependsOn(":web:jsBrowserProductionDist")
        inputs.dir(distDir)
    }
    doLast {
        val target = outDir.get().asFile.resolve("homegap/dashboard/WebAssets.kt")
        target.parentFile.mkdirs()
        // `.br` files are the brotli copies vite.config.js writes; they ride along with their file.
        val files = if (skipWeb) emptyList() else distDir.get().asFile.walkTopDown()
            .filter { it.isFile && it.extension != "br" }
            .sortedBy { it.path }
            .toList()
        val root = distDir.get().asFile
        val sb = StringBuilder()
        sb.appendLine("// GENERATED by :generateWebAssets. Do not edit.")
        sb.appendLine("package homegap.dashboard")
        sb.appendLine()
        sb.appendLine("internal object WebAssets {")
        sb.appendLine("    val files: Map<String, WebAsset> by lazy {")
        sb.appendLine("        mapOf(")
        files.forEachIndexed { i, f ->
            val path = "/" + f.relativeTo(root).invariantSeparatorsPath
            // Text assets also ship gzip-compressed; served as-is to clients that accept gzip.
            val gz = if (f.extension in setOf("js", "mjs", "css", "html", "svg", "json", "map", "wasm")) "gz$i()" else "null"
            val br = if (File("${f.path}.br").isFile) "br$i()" else "null"
            sb.appendLine("            \"$path\" to WebAsset(\"$path\", asset$i(), $gz, $br),")
        }
        sb.appendLine("        )")
        sb.appendLine("    }")
        files.forEachIndexed { i, f ->
            val b64 = Base64.getEncoder().encodeToString(f.readBytes())
            sb.appendLine("    private fun asset$i(): String = buildString {")
            b64.chunked(30_000).forEach { chunk -> sb.appendLine("        append(\"$chunk\")") }
            sb.appendLine("    }")
            if (f.extension in setOf("js", "mjs", "css", "html", "svg", "json", "map", "wasm")) {
                val bos = ByteArrayOutputStream()
                GZIPOutputStream(bos).use { it.write(f.readBytes()) }
                val gzb64 = Base64.getEncoder().encodeToString(bos.toByteArray())
                sb.appendLine("    private fun gz$i(): String = buildString {")
                gzb64.chunked(30_000).forEach { chunk -> sb.appendLine("        append(\"$chunk\")") }
                sb.appendLine("    }")
            }
            val brotliFile = File("${f.path}.br")
            if (brotliFile.isFile) {
                val brb64 = Base64.getEncoder().encodeToString(brotliFile.readBytes())
                sb.appendLine("    private fun br$i(): String = buildString {")
                brb64.chunked(30_000).forEach { chunk -> sb.appendLine("        append(\"$chunk\")") }
                sb.appendLine("    }")
            }
        }
        sb.appendLine("}")
        target.writeText(sb.toString())
    }
}

/** Embeds the shipped data-center catalog (`locations/datacenters.yml`) in the binary. */
val generateLocations by tasks.registering {
    val outDir = generatedLocationsDir
    val source = layout.projectDirectory.file("locations/datacenters.yml")
    inputs.file(source)
    outputs.dir(outDir)
    doLast {
        val target = outDir.get().asFile.resolve("homegap/locations/BuiltInLocations.kt")
        target.parentFile.mkdirs()
        val b64 = Base64.getEncoder().encodeToString(source.asFile.readBytes())
        target.writeText(buildString {
            appendLine("// GENERATED by :generateLocations from locations/datacenters.yml. Do not edit.")
            appendLine("package homegap.locations")
            appendLine()
            appendLine("internal object BuiltInLocations {")
            appendLine("    val yaml: String by lazy { kotlin.io.encoding.Base64.decode(BASE64).decodeToString() }")
            appendLine("    private const val BASE64 = \"$b64\"")
            appendLine("}")
        })
    }
}

tasks.matching { it.name.startsWith("compileKotlin") || it.name.endsWith("SourcesJar") }.configureEach {
    dependsOn(generateWebAssets, generateLocations)
}
